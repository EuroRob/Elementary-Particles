#!/usr/bin/env python3
"""
Vault lanes (IaC/docs/AGENT_ACCESS_LANES.md): render, check and apply the
policies that keep Claude Code on the infrastructure side.

    python3 scripts/vault_lanes.py check            # every live path is classified (exit 1 if not)
    python3 scripts/vault_lanes.py render           # vault/lanes.yml -> vault/policies/*.hcl
    python3 scripts/vault_lanes.py diff             # rendered vs. what Vault has now
    python3 scripts/vault_lanes.py apply --yes      # write the policies + the claude-iac token role
    python3 scripts/vault_lanes.py audit --yes      # turn on Vault's file audit log
    python3 scripts/vault_lanes.py issue --yes      # a claude-iac token -> ~/.config/vault/claude-iac.token
    python3 scripts/vault_lanes.py verify           # Vault's own answer: that token reads exactly the infra lane

`check` and `diff` read path NAMES and policy text only. `apply`, `audit` and
`issue` need a token allowed to manage policies (today: the root token) and are
the owner's to run -- see the doc's "Switching over".
"""

import argparse
import json
import os
import sys
from pathlib import Path

import requests
import yaml

HERE = Path(__file__).resolve().parent
IAC = HERE.parent
LANES = IAC / "vault" / "lanes.yml"
POLICY_DIR = IAC / "vault" / "policies"
VAULT = os.environ.get("VAULT_ADDR", "http://127.0.0.1:8200").rstrip("/")
TOKEN = os.environ.get("VAULT_TOKEN", "")
CLAUDE_TOKEN_FILE = Path(os.environ.get("CLAUDE_VAULT_TOKEN_FILE", "~/.config/vault/claude-iac.token")).expanduser()
HEADER = "# Generated by scripts/vault_lanes.py from vault/lanes.yml -- edit lanes.yml, then render.\n"


def load() -> dict:
    with open(LANES, encoding="utf-8") as f:
        return yaml.safe_load(f)


def lane_of(cfg: dict, path: str) -> str | None:
    """Lane for a path like 'homelab/podcast' (longest override wins, then top level)."""
    parts = path.strip("/").split("/")
    for i in range(len(parts), 1, -1):
        if (p := "/".join(parts[:i])) in cfg.get("overrides", {}):
            return cfg["overrides"][p]
    return cfg["paths"].get(parts[0])


def _caps(cfg: dict, lane: str) -> list[str]:
    return cfg["lanes"][lane]["claude"]


def render_claude(cfg: dict) -> str:
    out = [HEADER,
           "# Claude Code's token. Reads the infra lane only; may create (never read) a new\n"
           "# secret anywhere, so seeding a new service still works.\n\n",
           'path "secret/metadata/*" {\n  capabilities = ["list"]\n}\n\n',
           'path "secret/data/*" {\n  capabilities = ["create"]\n}\n']
    for top, lane in sorted(cfg["paths"].items()):
        if lane == "infra":
            caps = json.dumps([c for c in _caps(cfg, lane) if c != "list"])
            out.append(f'\npath "secret/data/{top}" {{\n  capabilities = {caps}\n}}\n'
                       f'path "secret/data/{top}/*" {{\n  capabilities = {caps}\n}}\n')
    for sub, lane in sorted(cfg.get("overrides", {}).items()):
        caps = json.dumps([c for c in _caps(cfg, lane) if c != "list"])
        out.append(f'\n# override: {sub} is {lane}\npath "secret/data/{sub}" {{\n  capabilities = {caps}\n}}\n'
                   f'path "secret/data/{sub}/*" {{\n  capabilities = {caps}\n}}\n')
    return "".join(out)


def render_runner() -> str:
    return (HEADER + "# The deploy runner (AppRole deploy-runner): reads every secret, as Ansible and\n"
            "# Terraform need. Its secret_id is readable only by the runner's Unix user; a run\n"
            "# needs the owner's sudo password. No delete, no policy or auth changes.\n\n"
            'path "secret/data/*" {\n  capabilities = ["create", "read", "update"]\n}\n\n'
            'path "secret/metadata/*" {\n  capabilities = ["list", "read"]\n}\n')


def vault(method: str, path: str, **kw) -> requests.Response:
    if not TOKEN:
        sys.exit("VAULT_TOKEN not set (source /opt/vault/.env in a subshell first)")
    return requests.request(method, f"{VAULT}/v1/{path}", headers={"X-Vault-Token": TOKEN}, timeout=15, **kw)


def live_paths(depth: int = 2) -> list[str]:
    """secret/ path names (not values), top level plus one level under each folder."""
    r = vault("LIST", "secret/metadata/")
    r.raise_for_status()
    out = []
    for k in r.json()["data"]["keys"]:
        out.append(k.rstrip("/"))
        if k.endswith("/") and depth > 1:
            sub = vault("LIST", f"secret/metadata/{k}")
            if sub.ok:
                out += [f"{k}{s}".rstrip("/") for s in sub.json()["data"]["keys"]]
    return out


def cmd_check(cfg: dict) -> int:
    bad = [p for p in live_paths() if lane_of(cfg, p) is None]
    lanes: dict[str, int] = {}
    for p in live_paths(depth=1):
        lanes[lane_of(cfg, p) or "UNCLASSIFIED"] = lanes.get(lane_of(cfg, p) or "UNCLASSIFIED", 0) + 1
    print("top-level paths per lane:", json.dumps(lanes, sort_keys=True))
    stale = [p for p in cfg["paths"] if p not in {x.split("/")[0] for x in live_paths(depth=1)}]
    if stale:
        print("in lanes.yml but not in Vault (fine, maybe retired):", ", ".join(sorted(stale)))
    if bad:
        print("UNCLASSIFIED (add to vault/lanes.yml):", ", ".join(sorted(bad)))
        return 1
    print("OK: every live path has a lane")
    return 0


def cmd_render(cfg: dict) -> int:
    POLICY_DIR.mkdir(parents=True, exist_ok=True)
    (POLICY_DIR / "claude-iac.hcl").write_text(render_claude(cfg))
    (POLICY_DIR / "deploy-runner.hcl").write_text(render_runner())
    print("wrote", ", ".join(sorted(p.name for p in POLICY_DIR.glob("*.hcl"))))
    return 0


def cmd_diff(cfg: dict) -> int:
    rc = 0
    for name, text in (("claude-iac", render_claude(cfg)), ("deploy-runner", render_runner())):
        r = vault("GET", f"sys/policies/acl/{name}")
        live = r.json()["data"]["policy"] if r.ok else None
        state = "missing in Vault" if live is None else ("same" if live == text else "DIFFERENT")
        print(f"{name}: {state}")
        rc |= state != "same"
    return rc


# No token_bound_cidrs yet: Vault runs in Docker, so local clients arrive from the
# bridge address, not 10.10.0.15. Read the real remote_address from the audit log
# (step 0) first, then bind the AppRoles to it.
def cmd_apply(cfg: dict) -> int:
    for name, text in (("claude-iac", render_claude(cfg)), ("deploy-runner", render_runner())):
        vault("PUT", f"sys/policies/acl/{name}", json={"policy": text}).raise_for_status()
        print(f"policy {name}: written")
    # Claude's tokens: periodic (renewable while used), orphan, claude-iac only.
    vault("POST", "auth/token/roles/claude-iac", json={
        "allowed_policies": ["claude-iac"], "orphan": True, "renewable": True,
        "token_period": "8h", "token_explicit_max_ttl": "168h", "token_type": "service"}).raise_for_status()
    print("token role claude-iac: written (period 8h, max 7 days)")
    # Same lane for Terraform/Ansible run by Claude Code (envs log in with AppRole):
    # TF_VAR_role_id/secret_id in Claude's env point here instead of at "terraform".
    vault("POST", "auth/approle/role/claude-iac", json={
        "token_policies": ["claude-iac"], "token_ttl": "1h", "token_max_ttl": "4h",
        "secret_id_ttl": "720h"}).raise_for_status()
    print("approle claude-iac: written (same policy, for Terraform/Ansible runs)")
    # The deploy runner's AppRole; its secret_id is fetched by owner into the runner's file.
    vault("POST", "auth/approle/role/deploy-runner", json={
        "token_policies": ["deploy-runner"], "token_ttl": "1h", "token_max_ttl": "4h",
        "secret_id_ttl": "720h"}).raise_for_status()
    print("approle deploy-runner: written (secret_id valid 30 days)")
    return 0


def cmd_audit() -> int:
    have = vault("GET", "sys/audit").json().get("data", {})
    if "file/" in have:
        print("audit device file/: already on")
        return 0
    vault("PUT", "sys/audit/file", json={"type": "file", "options": {
        "file_path": "/vault/logs/audit.log", "mode": "0600"}}).raise_for_status()
    print("audit device file/: on -> /opt/vault/logs/audit.log (values HMAC'd, not stored)")
    return 0


def cmd_issue() -> int:
    r = vault("POST", "auth/token/create/claude-iac", json={"display_name": "claude-code", "meta": {"who": "claude-code"}})
    r.raise_for_status()
    CLAUDE_TOKEN_FILE.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(CLAUDE_TOKEN_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(r.json()["auth"]["client_token"] + "\n")
    print(f"claude-iac token written to {CLAUDE_TOKEN_FILE} (0600); policies:", r.json()["auth"]["policies"])
    return 0


def cmd_verify(cfg: dict) -> int:
    """With the issued claude-iac token: Vault's own answer (sys/capabilities-self)
    for every top-level path. Infra must be readable; nothing else may be."""
    tok = CLAUDE_TOKEN_FILE.read_text().strip()
    paths = [f"secret/data/{p}/x" for p in cfg["paths"]] + [f"secret/data/{p}" for p in cfg.get("overrides", {})]
    r = requests.post(f"{VAULT}/v1/sys/capabilities-self", headers={"X-Vault-Token": tok},
                      json={"paths": paths}, timeout=15)
    r.raise_for_status()
    caps, bad = r.json(), []
    for p in paths:
        rel = p.removeprefix("secret/data/").removesuffix("/x")
        can_read = "read" in caps.get(p, [])
        want = lane_of(cfg, rel) == "infra"
        if can_read != want:
            bad.append(f"{rel}: read={can_read}, expected {want}")
    print("\n".join(bad) if bad else f"OK: {len(paths)} paths, claude-iac reads exactly the infra lane")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["check", "render", "diff", "apply", "audit", "issue", "verify"])
    ap.add_argument("--yes", action="store_true", help="required for apply/audit/issue")
    a = ap.parse_args()
    cfg = load()
    if a.cmd in ("apply", "audit", "issue") and not a.yes:
        sys.exit(f"{a.cmd} changes Vault; re-run with --yes")
    return {"check": lambda: cmd_check(cfg), "render": lambda: cmd_render(cfg), "diff": lambda: cmd_diff(cfg),
            "apply": lambda: cmd_apply(cfg), "audit": cmd_audit, "issue": cmd_issue,
            "verify": lambda: cmd_verify(cfg)}[a.cmd]()


if __name__ == "__main__":
    sys.exit(main())
